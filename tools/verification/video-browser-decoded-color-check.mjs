/** Real MP4 -> shared movie selection -> WebCodecs -> GPU color/display, checked
 * against independently verified native linear samples of the same raw PTS. */
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createServer } from 'node:http';
import { resolve } from 'node:path';
import { chromium } from 'playwright-core';
import { createHash } from 'node:crypto';
const [visualPath, mediaPath, indexPath, fixturePath, linearPath, outputPath] = process.argv.slice(2);
assert(outputPath, 'usage: visual media index fixture linear-rgb.f32 new-output');
const output = resolve(outputPath); await mkdir(output);
const routes = new Map(), pins = {};
for (const [prefix, directory] of [['visual', visualPath], ['media', mediaPath], ['index', indexPath]]) {
  const bytes = await readFile(resolve(directory, 'bundle-manifest.json'));
  pins[prefix] = createHash('sha256').update(bytes).digest('hex');
  for (const file of JSON.parse(bytes).files) if (/\.(mjs|js|wasm)$/.test(file.path)) routes.set(`/${prefix}/${file.path}`, await readFile(resolve(directory, file.path)));
}
const fixture = await readFile(fixturePath), linear = await readFile(linearPath);
const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-ignore_editlist', '1', '-select_streams', 'v:0', '-show_frames', '-show_streams', '-of', 'json', fixturePath], { maxBuffer: 8 << 20 }));
const { width, height } = probe.streams[0]; assert.equal(linear.length, probe.frames.length * width * height * 12);
routes.set('/fixture', fixture); routes.set('/linear', linear);
routes.set('/worker.mjs', Buffer.from(`
import { createVisualRuntime } from '/visual/index.mjs';
import { BrowserGpuExecutor } from '/visual/client/index.js';
import { BrowserMediaInput, BrowserMediaBudget } from '/media/index.mjs';
import { createMediaIndexRuntime } from '/index/index.mjs';
self.onmessage = async ({data}) => {
 let gpu, input;
 try {
  const runtime = await createVisualRuntime(await WebAssembly.compileStreaming(fetch('/visual/runtime/mo_video_visual_wasm_bg.wasm')));
  const index = await createMediaIndexRuntime(await WebAssembly.compileStreaming(fetch('/index/runtime/mo_media_index_wasm_bg.wasm')));
  const adapter = await navigator.gpu.requestAdapter(); if (!adapter || adapter.info.isFallbackAdapter) throw Error('real GPU unavailable');
  gpu = await BrowserGpuExecutor.create(adapter, runtime.composition_shader()); await gpu.configureColor(JSON.parse(runtime.color_shaders()));
  const budget = new BrowserMediaBudget(32 << 20);
  input = await BrowserMediaInput.open(await (await fetch('/fixture')).blob(), {mediaIndexRuntime:index, mediaBudget:budget});
  const track = input.info.tracks.find(x => x.kind === 'video');
  const reference = new Float32Array(await (await fetch('/linear')).arrayBuffer());
  const rows = [];
  for (const frameIndex of [...data.requests.keys(), 40, 17, 0]) {
    let actual, format, colorSpace, bitmap;
    // Movie times are independently generated by ffprobe's edit-aware PTS.
    const request = data.requests[frameIndex];
    const selection = await input.movieVideoAt(track.id, request, async (sample) => {
      const lease = sample.cloneFrame(); format = lease.frame.format; colorSpace = lease.frame.colorSpace.toJSON();
      const chromaLocation = sample.codecMetadata?.chromaLocation;
      if (!chromaLocation) { lease.close(); throw Error('shared codec metadata missing'); }
      const image = await gpu.importVideo(lease, JSON.parse(runtime.video_input_plan(JSON.stringify({width:sample.width,height:sample.height,format,colorSpace,chromaLocation}))));
      try {
        actual = await gpu.readback(image);
        bitmap = await gpu.toBitmap(image,JSON.parse(runtime.srgb_output_parameters(sample.width,sample.height,false,undefined,true)));
        bitmap.close();
      } finally { image.close(); }
    });
    if (!actual || selection.type !== 'sample') throw Error('expected frame');
    const ordinal = data.rawPts.indexOf(selection.rawStart); if (ordinal < 0) throw Error('unknown raw PTS');
    const expected = reference.subarray(ordinal*data.width*data.height*3,(ordinal+1)*data.width*data.height*3);
    let maximum=0,square=0,absolute=0;
    for (let p=0;p<data.width*data.height;p++) for(let c=0;c<3;c++) {const d=Math.abs(actual[p*4+c]-expected[p*3+c]);maximum=Math.max(maximum,d);square+=d*d;absolute+=d;}
    rows.push({frameIndex,ordinal,rawPts:selection.rawStart,format,colorSpace,maximum,rms:Math.sqrt(square/expected.length),mae:absolute/expected.length});
  }
  input.close(); gpu.close();
  for(let i=0;i<100 && budget.usedBytes;i++) await new Promise(r=>setTimeout(r,10));
  self.postMessage({ok:true,rows,budget:{used:budget.usedBytes,peak:budget.peakBytes},gpu:{buffers:gpu.allocatedBytes,surfaces:gpu.retainedSurfaceBytes}});
 } catch(e) {self.postMessage({ok:false,error:String(e),stack:e.stack});} finally {input?.close();gpu?.close();}
};`));
const server = createServer((q, r) => {
  if (q.url === '/') {r.setHeader('Content-Type', 'text/html');r.end('<!doctype html>');return;}
  const bytes = routes.get(q.url); if (!bytes) {r.writeHead(404);r.end();return;}
  r.setHeader('Content-Type', q.url.endsWith('.wasm') ? 'application/wasm' : /\.m?js$/.test(q.url) ? 'text/javascript' : 'application/octet-stream');r.end(bytes);
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--enable-unsafe-webgpu']});
try {
  const page = await browser.newPage();await page.goto(`http://127.0.0.1:${server.address().port}`);
  const movieProbe = JSON.parse(execFileSync('ffprobe',['-v','error','-select_streams','v:0','-show_frames','-show_streams','-of','json',fixturePath],{maxBuffer:8<<20}));
  const timebase = movieProbe.streams[0].time_base.split('/').map(BigInt);
  const requests = movieProbe.frames.map(f=>({time:{numerator:String(BigInt(f.pts)*timebase[0]),denominator:String(timebase[1])},side:'after'}));
  const result = await page.evaluate(data=>new Promise((resolve,reject)=>{
    const worker=new Worker('/worker.mjs',{type:'module'}),timer=setTimeout(()=>{worker.terminate();reject(Error('deadline'));},60000);
    worker.onmessage=e=>{clearTimeout(timer);worker.terminate();resolve(e.data);};worker.onerror=e=>{clearTimeout(timer);worker.terminate();reject(Error(e.message));};worker.postMessage(data);
  }),{width,height,requests,rawPts:probe.frames.map(f=>String(f.pts))});
  const report={format:'musteroffice.video-browser-decoded-color-check/1',browser:browser.version(),pins,fixtureSha256:createHash('sha256').update(fixture).digest('hex'),referenceSha256:createHash('sha256').update(linear).digest('hex'),...result};
  let checkError;
  try {
    assert(result.ok,JSON.stringify(result));
    assert.equal(result.budget.used,0);assert.equal(result.gpu.buffers,0);assert.equal(result.gpu.surfaces,0);
    for(const row of result.rows) assert(row.maximum<2e-5 && row.rms<2e-6, `Decoded color mismatch at ${row.ordinal}: ${row.maximum}/${row.rms}`);
  } catch(error){checkError=error;}
  report.status=checkError?'failed':'passed';
  report.scope='Real WebCodecs H.264 movie selection, shared per-picture chroma metadata and raw-plane GPU normalization plus bitmap production; reference native linear samples independently validated against FFmpeg. Not complete colour-override policy, UI playback, zero-copy or performance acceptance.';
  await writeFile(output+'/report.json',JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
  if(checkError) throw checkError;

}finally{await browser.close();await new Promise(r=>server.close(r));}
